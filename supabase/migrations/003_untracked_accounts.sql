-- ===============================================
-- 003. Счета вне учёта
-- ===============================================
-- Деньги, переведённые на такой счёт, считаются ушедшими из бюджета,
-- а возврат с него — поступлением. Его баланс нигде не показывается
-- и не сверяется (например, личный счёт, куда откладываются остатки).
-- Каждый оператор самостоятельный, повторный запуск безопасен.

alter table public.accounts
  add column if not exists track_balance boolean not null default true;

update public.accounts
set track_balance = false
where system_key = 'legacy_leftovers';
